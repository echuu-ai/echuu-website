export type SiteTranslationKey = keyof typeof siteTranslations.en;

export function useSiteI18n() {
  const locale = useI18nStore((state) => state.locale);
  const setLocale = useI18nStore((state) => state.setLocale);
  const t = useCallback(
    (key: SiteTranslationKey) => siteTranslations[locale][key] ?? siteTranslations.en[key],
    [locale],
  );
  const tf = useCallback(
    (key: SiteTranslationKey, vars: Record<string, string | number>) => formatSiteText(t(key), vars),
    [t],
  );
  return { locale, setLocale, t, tf };
}

/** Replace `{name}` placeholders in a translated string. Missing keys are left as-is. */
export function formatSiteText(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Read a translation outside React (class components, module helpers). */
export function getSiteText(key: SiteTranslationKey, locale: Locale = useI18nStore.getState().locale) {
  return siteTranslations[locale][key] ?? siteTranslations.en[key];
}
