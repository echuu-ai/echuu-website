import { create } from 'zustand';

export type Locale = 'zh' | 'en' | 'ja' | 'ko';

type I18nState = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
};

export const useI18nStore = create<I18nState>((set) => {
  let defaultLocale: Locale = 'zh';
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('echuu-locale') as Locale;
    if (saved && ['zh', 'en', 'ja', 'ko'].includes(saved)) {
      defaultLocale = saved;
    } else {
      const navLang = navigator.language.toLowerCase();
      if (navLang.startsWith('en')) defaultLocale = 'en';
      else if (navLang.startsWith('ja')) defaultLocale = 'ja';
      else if (navLang.startsWith('ko')) defaultLocale = 'ko';
    }
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = defaultLocale === 'zh' ? 'zh-CN' : defaultLocale;
  }

  return {
    locale: defaultLocale,
    setLocale: (locale) => {
      if (typeof window !== 'undefined') {
        localStorage.setItem('echuu-locale', locale);
      }
      if (typeof document !== 'undefined') {
        document.documentElement.lang = locale === 'zh' ? 'zh-CN' : locale;
      }
      set({ locale });
    },
  };
});

